"""Document RAG engine adapted from the course ChatPDF/Streamlit exercise.

Retrieval works locally with TF-IDF. When OPENAI_API_KEY is configured, the
index uses OpenAI embeddings and answers are generated by an OpenAI chat model.
"""
from __future__ import annotations

from dataclasses import dataclass
from io import BytesIO
from typing import Iterable, Optional

import numpy as np
from pypdf import PdfReader
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import cosine_similarity


@dataclass(frozen=True)
class Chunk:
    text: str
    source: str
    page: Optional[int] = None


@dataclass(frozen=True)
class RetrievedChunk:
    text: str
    source: str
    page: Optional[int]
    score: float


def extract_pages(filename: str, content: bytes) -> list[tuple[str, Optional[int]]]:
    """Extract text from PDF, TXT or Markdown uploads, preserving PDF pages."""
    lower = filename.lower()
    if lower.endswith(".pdf"):
        reader = PdfReader(BytesIO(content))
        pages: list[tuple[str, Optional[int]]] = []
        for index, page in enumerate(reader.pages, start=1):
            text = (page.extract_text() or "").strip()
            if text:
                pages.append((text, index))
        return pages
    if lower.endswith((".txt", ".md")):
        text = content.decode("utf-8-sig", errors="replace").strip()
        return [(text, None)] if text else []
    raise ValueError(f"Formato não suportado: {filename}. Envie PDF, TXT ou MD.")


def split_text(text: str, chunk_size: int = 1000, overlap: int = 150) -> list[str]:
    """Split text into overlapping character chunks without empty fragments."""
    if chunk_size < 100:
        raise ValueError("chunk_size deve ser >= 100")
    if overlap < 0 or overlap >= chunk_size:
        raise ValueError("overlap deve estar entre 0 e chunk_size - 1")
    normalized = " ".join(text.split())
    if not normalized:
        return []
    chunks: list[str] = []
    start = 0
    while start < len(normalized):
        end = min(start + chunk_size, len(normalized))
        if end < len(normalized):
            boundary = normalized.rfind(" ", start + chunk_size // 2, end)
            if boundary > start:
                end = boundary
        piece = normalized[start:end].strip()
        if piece:
            chunks.append(piece)
        if end >= len(normalized):
            break
        start = max(end - overlap, start + 1)
    return chunks


class DocumentRAG:
    def __init__(
        self,
        api_key: Optional[str] = None,
        chat_model: str = "gpt-4o-mini",
        embedding_model: str = "text-embedding-3-small",
        client=None,
    ) -> None:
        self.api_key = api_key or None
        self.chat_model = chat_model
        self.embedding_model = embedding_model
        self.client = client
        if self.client is None and self.api_key:
            try:
                from openai import OpenAI
            except ImportError as exc:
                raise RuntimeError("Instale as dependências com: pip install -r requirements.txt") from exc
            self.client = OpenAI(api_key=self.api_key)
        self.chunks: list[Chunk] = []
        self._vectorizer: Optional[TfidfVectorizer] = None
        self._tfidf_matrix = None
        self._embeddings: Optional[np.ndarray] = None

    @property
    def mode(self) -> str:
        return "OpenAI embeddings + geração por LLM" if self.client else "Recuperação local TF-IDF (sem geração por LLM)"

    def add_files(self, files: Iterable[tuple[str, bytes]]) -> int:
        new_chunks: list[Chunk] = []
        for filename, content in files:
            for page_text, page_number in extract_pages(filename, content):
                for part in split_text(page_text):
                    new_chunks.append(Chunk(part, filename, page_number))
        if not new_chunks:
            raise ValueError("Não foi encontrado texto extraível nos arquivos enviados.")
        self.chunks.extend(new_chunks)
        self._build_index()
        return len(new_chunks)

    def _build_index(self) -> None:
        texts = [chunk.text for chunk in self.chunks]
        self._vectorizer = None
        self._tfidf_matrix = None
        self._embeddings = None
        if self.client:
            # Batch requests to keep request sizes bounded.
            vectors: list[list[float]] = []
            for start in range(0, len(texts), 64):
                response = self.client.embeddings.create(
                    model=self.embedding_model,
                    input=texts[start : start + 64],
                )
                vectors.extend(item.embedding for item in response.data)
            self._embeddings = np.asarray(vectors, dtype=np.float32)
        else:
            self._vectorizer = TfidfVectorizer(ngram_range=(1, 2), strip_accents="unicode")
            self._tfidf_matrix = self._vectorizer.fit_transform(texts)

    def retrieve(self, query: str, top_k: int = 4) -> list[RetrievedChunk]:
        if not self.chunks:
            raise ValueError("Envie e indexe pelo menos um documento antes de perguntar.")
        if not query.strip():
            raise ValueError("A pergunta não pode ficar vazia.")
        if self.client:
            response = self.client.embeddings.create(model=self.embedding_model, input=[query])
            query_vector = np.asarray(response.data[0].embedding, dtype=np.float32).reshape(1, -1)
            scores = cosine_similarity(query_vector, self._embeddings)[0]
        else:
            query_vector = self._vectorizer.transform([query])
            scores = cosine_similarity(query_vector, self._tfidf_matrix)[0]
        ranked = np.argsort(scores)[::-1][: max(1, min(top_k, len(self.chunks)))]
        results = [
            RetrievedChunk(
                text=self.chunks[i].text,
                source=self.chunks[i].source,
                page=self.chunks[i].page,
                score=float(scores[i]),
            )
            for i in ranked
            if float(scores[i]) > 0
        ]
        return results

    def answer(self, question: str, top_k: int = 4) -> tuple[str, list[RetrievedChunk]]:
        retrieved = self.retrieve(question, top_k=top_k)
        if not retrieved:
            return (
                "Não encontrei trechos relevantes nos documentos indexados. Reformule a pergunta "
                "ou envie um documento que contenha essa informação.",
                [],
            )
        context = "\n\n".join(
            f"[Fonte: {item.source}{', página ' + str(item.page) if item.page else ''}]\n{item.text}"
            for item in retrieved
        )
        if not self.client:
            excerpts = "\n\n".join(
                f"**{item.source}{' — página ' + str(item.page) if item.page else ''}**\n{item.text}"
                for item in retrieved[:3]
            )
            return (
                "**Modo local:** a busca recuperou os trechos abaixo. Configure `OPENAI_API_KEY` "
                "para habilitar a geração de respostas por LLM.\n\n" + excerpts,
                retrieved,
            )
        response = self.client.chat.completions.create(
            model=self.chat_model,
            temperature=0.1,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "Você é um assistente de consulta documental. Responda em português, "
                        "usando somente o contexto fornecido. Se o contexto não sustentar a resposta, "
                        "diga explicitamente que não encontrou a informação. Não invente fatos, "
                        "números, datas ou fontes. Cite o nome do arquivo e a página quando disponível."
                    ),
                },
                {
                    "role": "user",
                    "content": f"CONTEXTO DOCUMENTAL:\n{context}\n\nPERGUNTA:\n{question}",
                },
            ],
        )
        answer = response.choices[0].message.content or "O modelo não retornou conteúdo."
        return answer, retrieved
